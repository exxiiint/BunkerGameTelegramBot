def generate_bunker_cards(rng: random.Random | None = None) -> List[BunkerCardData]:
    rng = rng or random.Random()
    picks = rng.sample(_BUNKER_POOL, 5)
    cards: List[BunkerCardData] = []
    for idx, (title, body) in enumerate(picks, start=1):
        cards.append(BunkerCardData(slot_no=idx, title=title, body=body))
    return cards
