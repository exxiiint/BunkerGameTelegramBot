def _ensure_enough(pool: list[str], n: int, category: str) -> None:
    if len(pool) < n:
        raise RuntimeError(
            f"Not enough cards in category '{category}': have {len(pool)}, need {n}."
        )


def generate_character_cards(players_count: int, rng: random.Random | None = None) -> Dict[int, List[CardData]]:
    """Generate a fixed set of 5 character cards per seat."""
    rng = rng or random.Random()

    _ensure_enough(_PROFESSIONS, players_count, "profession")
    _ensure_enough(_HEALTH, players_count, "health")
    _ensure_enough(_HOBBIES, players_count, "hobby")
    _ensure_enough(_TRAITS, players_count, "trait")
    _ensure_enough(_INVENTORY, players_count, "inventory")

    professions = rng.sample(_PROFESSIONS, players_count)
    health = rng.sample(_HEALTH, players_count)
    hobbies = rng.sample(_HOBBIES, players_count)
    traits = rng.sample(_TRAITS, players_count)
    inventory = rng.sample(_INVENTORY, players_count)

    per_seat: Dict[int, List[CardData]] = {}
    for i in range(players_count):
        seat = i + 1
        per_seat[seat] = [
            CardData("profession", "Профессия", professions[i]),
            CardData("health", "Здоровье", health[i]),
            CardData("hobby", "Хобби", hobbies[i]),
            CardData("trait", "Черта характера", traits[i]),
            CardData("inventory", "Багаж", inventory[i]),
        ]
    return per_seat


